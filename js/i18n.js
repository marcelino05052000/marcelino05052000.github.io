const STORAGE_KEY = 'mbc-lang';
const FALLBACK = 'en';

function detectLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && translations[stored]) return stored;
  const browser = (navigator.language || navigator.userLanguage || '').toLowerCase();
  if (browser.startsWith('pt')) return 'pt';
  return FALLBACK;
}

function applyLang(lang) {
  const dict = translations[lang] || translations[FALLBACK];

  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';

  if (dict['meta.title']) {
    document.title = dict['meta.title'];
  }

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  const footerEl = document.querySelector('[data-i18n-template="footer.text"]');
  if (footerEl && dict['footer.text']) {
    footerEl.innerHTML = dict['footer.text'].replace('{year}', new Date().getFullYear());
  }

  document.querySelectorAll('.lang-toggle [data-lang]').forEach((btn) => {
    const isActive = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('active', isActive);
    btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
  });

  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (_) {
    /* ignore quota / privacy errors */
  }
}

document.addEventListener('DOMContentLoaded', () => {
  applyLang(detectLang());
  document.querySelectorAll('.lang-toggle [data-lang]').forEach((btn) => {
    btn.addEventListener('click', () => applyLang(btn.getAttribute('data-lang')));
  });
});
